def split(lines):
    """By time: the first 60% of bank lines train, the next 20% validate, the last 20% test."""
    a, b = lines.day.quantile([.6, .8])
    return lines[lines.day <= a].line, lines[(lines.day > a) & (lines.day <= b)].line, lines[lines.day > b].line


def recall_of(pairs, links):
    got = links.merge(pairs[["line", "invoice"]], on=["line", "invoice"])
    return len(got) / len(links)


