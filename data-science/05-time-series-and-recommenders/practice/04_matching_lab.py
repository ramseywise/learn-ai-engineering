def subset_sum(cands, target, max_items=4, tol=.005):
    """All subsets of up to max_items candidate invoices whose amounts add up to the payment."""
    amounts, idx = cands.amount.to_numpy(), cands.invoice.to_numpy()
    found = []

    def go(i, left, chosen):
        if len(found) > 20:
            return
        if abs(left) < tol and chosen:
            found.append(tuple(chosen))
            return
        if len(chosen) == max_items:
            return
        for j in range(i, len(amounts)):
            if amounts[j] <= left + tol:
                go(j + 1, left - amounts[j], chosen + [idx[j]])
    go(0, target, [])
    return found


