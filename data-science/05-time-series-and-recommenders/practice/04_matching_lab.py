# %% Fellegi-Sunter weights
def agreement(p):
    """Coded agreement on each component, the comparison vector in the 1969 paper."""
    return pd.DataFrame({
        "amount": np.select([p.amount_exact == 1, p.amount_near == 1], ["exact", "within 3%"], "far"),
        "name": np.select([p.name_sim >= .6, p.name_sim >= .25], ["strong", "weak"], "none"),
        "reference": np.select([p.ref_digits == 6, p.ref_digits == 5, p.ref_digits == -1], ["all digits", "one digit off", "missing"], "other"),
        "date": np.select([p.days_from_due <= 25, p.days_from_due <= 60], ["near due", "later"], "far")}, index=p.index)


def fit_fs(p, a):
    w = {}
    for c in a.columns:
        m = a.loc[p.linked == 1, c].value_counts(normalize=True)
        u = a.loc[p.linked == 0, c].value_counts(normalize=True)
        w[c] = np.log2((m.reindex(u.index.union(m.index)).fillna(0) + 1e-4) / (u.reindex(u.index.union(m.index)).fillna(0) + 1e-4))
        if c == "reference":
            w[c]["missing"] = 0.0                               # the 1969 paper's rule: missing carries no weight
    return w


def score_fs(a, w):
    return sum(a[c].map(w[c]).fillna(0).to_numpy() for c in a.columns)


