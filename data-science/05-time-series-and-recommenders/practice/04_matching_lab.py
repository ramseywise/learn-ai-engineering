# %% Ranking objectives
def lin(p, scaler=None):
    X = np.column_stack([np.log1p(p.amount_rel_diff), p.amount_exact, p.amount_near, np.log1p(p.days_since_issue.clip(0)),
                         np.log1p(p.days_from_due), p.name_sim, p.ref_digits == 6, p.ref_digits == 5, p.ref_digits == -1,
                         np.log(p.amount_rank), np.log(p.name_rank), np.log(p.n_candidates)]).astype(float)
    scaler = scaler or StandardScaler().fit(X)
    return scaler.transform(X), scaler


def pair_diffs(X, y, g, rng, per_group=30):
    """RankNet's training set for a linear model: feature differences for pairs with different grades, within a line."""
    out = []
    for k in np.unique(g):
        i = np.flatnonzero(g == k)
        hi, lo = i[y[i] > 0], i
        a = rng.choice(hi, per_group) if len(hi) else []
        b = rng.choice(lo, per_group)
        for u, v in zip(a, b):
            if y[u] > y[v]:
                out.append(X[u] - X[v])
    return np.array(out)


def boosted_pairs(delta):
    """Custom LightGBM objective: RankNet's gradients, and with delta=True the |change in NDCG| factor as well."""
    def f(preds, ds):
        y, sizes = ds.get_label(), ds.get_group()
        grad, hess = np.zeros_like(preds), np.zeros_like(preds)
        start = 0
        for n in sizes:
            n = int(n)
            s, g = preds[start:start + n], y[start:start + n]
            hi = np.flatnonzero(g > 0)
            if len(hi):
                rho = 1 / (1 + np.exp(s[hi, None] - s[None, :]))
                mask = g[hi, None] > g[None, :]
                wt = 1.0
                if delta:
                    rank = np.empty(n, int)
                    rank[np.argsort(-s, kind="stable")] = np.arange(n)
                    disc = 1 / np.log2(rank + 2)
                    gain = 2.0 ** g - 1
                    ideal = (np.sort(gain)[::-1] / np.log2(np.arange(n) + 2)).sum()
                    wt = np.abs((gain[hi, None] - gain[None, :]) * (disc[hi, None] - disc[None, :])) / ideal
                lam, h = rho * mask * wt, rho * (1 - rho) * mask * wt
                grad[start:start + n][hi] -= lam.sum(1)
                grad[start:start + n] += lam.sum(0)
                hess[start:start + n][hi] += h.sum(1)
                hess[start:start + n] += h.sum(0)
            start += n
        return grad, np.maximum(hess, 1e-6)
    return f


def ranker(objective, Xtr, ytr, gtr, seed):
    sizes = pd.Series(gtr).value_counts(sort=False).to_numpy()
    ds = lgb.Dataset(Xtr, label=ytr, group=sizes, free_raw_data=False)
    return lgb.train(dict(GBM, objective=objective, seed=seed, label_gain=[0, 1, 3]), ds, ROUNDS)


def fit_all(ptr, seed):
    """Fit every model on the lines that have a true link, and return a scoring function per model."""
    q = ptr[ptr.groupby("line").linked.transform("max") == 1].sort_values(["line", "invoice"])
    Xq, y, g, ybin = q[FEATURES].to_numpy(float), q.grade.to_numpy(), q.line.to_numpy(), q.linked.to_numpy()
    Xl, sc = lin(q)
    rng = np.random.default_rng(seed)
    Xall = ptr[FEATURES].to_numpy(float)
    Xla, _ = lin(ptr, sc)
    models = {}
    models["Closest amount"] = lambda t: -t.amount_rel_diff.to_numpy()
    w = fit_fs(ptr, agreement(ptr))
    models["Fellegi-Sunter weights"] = lambda t: score_fs(agreement(t), w)
    lr = LogisticRegression(max_iter=2000).fit(Xla, ptr.linked)
    models["Pointwise linear"] = lambda t: lr.decision_function(lin(t, sc)[0])
    d = pair_diffs(Xl, y, g, rng)
    rn = LogisticRegression(fit_intercept=False, max_iter=2000).fit(np.vstack([d, -d]), np.r_[np.ones(len(d)), np.zeros(len(d))])
    models["Pairwise linear (RankNet)"] = lambda t: rn.decision_function(lin(t, sc)[0])
    pt = lgb.train(dict(GBM, objective="binary", seed=seed), lgb.Dataset(Xall, label=ptr.linked), ROUNDS)
    models["Pointwise trees"] = lambda t: pt.predict(t[FEATURES].to_numpy(float), raw_score=True)
    rb = ranker(boosted_pairs(False), Xq, y, g, seed)
    models["Pairwise trees (no NDCG factor)"] = lambda t: rb.predict(t[FEATURES].to_numpy(float), raw_score=True)
    cu = ranker(boosted_pairs(True), Xq, y, g, seed)
    models["Pairwise trees + NDCG factor"] = lambda t: cu.predict(t[FEATURES].to_numpy(float), raw_score=True)
    lm = ranker("lambdarank", Xq, y, g, seed)
    models["LambdaMART (LightGBM)"] = lambda t: lm.predict(t[FEATURES].to_numpy(float))
    xe = ranker("rank_xendcg", Xq, y, g, seed)
    models["Listwise trees (XE-NDCG)"] = lambda t: xe.predict(t[FEATURES].to_numpy(float))
    return models


