"""The numbers in notes/02b: fine-tuning a small vision-language model to read generated invoices, end to end.

Run from this folder (downloads SmolVLM-256M-Instruct, about 0.5 GB, on first use; about two and a half hours on an Apple M4 Pro GPU with nothing else running):
    uv run vlm_finetune_lab.py
    uv run vlm_finetune_lab.py --seeds 1 --steps 6    # a smoke test of every step, about fifteen minutes on an idle machine, twice that or more if other work is running
    uv run vlm_finetune_lab.py --probes               # clean timings and why a 4-bit merge fails, about twenty minutes on an idle machine, far longer if not
    uv run vlm_finetune_lab.py --frozen               # what the 70-token reply limit does to the frozen scores, 3 seeds

Every invoice is generated by vlm_invoices.py, so labels are correct by construction and nothing real is in them.
"""
# %%
import argparse
import logging
import sys
import tempfile
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import numpy as np
import pandas as pd
import torch
from peft import PeftModel
from peft.utils.integrations import dequantize_bnb_weight

from vlm_finetune import DEVICE, MODEL, PROMPT, SHOWN, SUFFIXES, TEXT_ONLY, add_lora, clear, driver_gb, weights_gb, load_model, load_processor, score, train
from vlm_invoices import LAYOUTS, NEW_STEMS, NEW_TRADES, answer, make

args = argparse.ArgumentParser()
args.add_argument("--seeds", type=int, default=3)
args.add_argument("--steps", type=int, default=200)
args.add_argument("--probes", action="store_true")
args.add_argument("--frozen", action="store_true")
args = args.parse_args()
SEEN, HELD_OUT = LAYOUTS[:3], LAYOUTS[3:]
N_TEST, STEPS = 40, args.steps
pd.set_option("display.width", 170)
started = time.time()
print(f"device {DEVICE}, model {MODEL}, {STEPS} steps, batch 4, lr 2e-4, LoRA r=8, one 512 px tile per page, {N_TEST} test invoices per slice")
proc = load_processor(512)


def size_mb(path):
    return sum(f.stat().st_size for f in Path(path).rglob("*") if f.is_file()) / 1e6


def trainable(model):
    return sum(p.numel() for p in model.parameters() if p.requires_grad)


# %% Frozen, at the reply limit the trained arms use and at one long enough not to cut its replies
if args.frozen:
    frozen, found = load_model(), []
    for seed in range(args.seeds):
        docs = make(N_TEST, seed + 1000, SEEN)
        for name, prompt in (("plain prompt", PROMPT), ("shape shown", SHOWN)):
            for limit in (70, 400):
                result, replies = score(frozen, proc, docs, prompt, limit)
                sizes = [len(proc.tokenizer(r, add_special_tokens=False).input_ids) for r in replies]
                found.append(dict(seed=seed, prompt=name, limit=limit, field_accuracy=result["field_accuracy"], values_found=result["values_found"], parses=result["parses"],
                                  median_tokens=float(np.median(sizes)), at_limit=float(np.mean([n >= limit - 1 for n in sizes]))))
                print(found[-1], flush=True)
    print(pd.DataFrame(found).groupby(["prompt", "limit"])[["field_accuracy", "values_found", "parses", "median_tokens", "at_limit"]].mean().round(3).to_string())
    print(pd.DataFrame(found).groupby(["prompt", "limit"])["field_accuracy"].agg(list).to_string())
    sys.exit()

# %% Probes, run alone so nothing else shares the GPU: seconds per step, then what a merge does to a 4-bit weight
if args.probes:
    docs, sized = make(400, 0, SEEN), load_processor(1024)
    print("--- seconds per step over 50 steps, twice, no scoring inside the timing. Other work on the machine shows up here: use the lower")
    for name, bits, targets, processor, batch in (("bf16, language model, 512, batch 4", None, TEXT_ONLY, proc, 4), ("bf16, language and vision, 512, batch 4", None, SUFFIXES, proc, 4),
                                                  ("4-bit, language model, 512, batch 4", 4, TEXT_ONLY, proc, 4), ("bf16, language model, 512, batch 2", None, TEXT_ONLY, proc, 2), ("bf16, language model, 1024, batch 2", None, TEXT_ONLY, sized, 2)):
        times = []
        for repeat in range(2):
            clear()
            model = add_lora(load_model(bits=bits), targets, quantized=bits == 4)
            times.append(train(model, processor, docs, 50, repeat, batch=batch))
            del model
        print(f"{name}: {times[0]:.2f}, {times[1]:.2f} s/step")
    clear()
    model = add_lora(load_model(bits=4), TEXT_ONLY, quantized=True)
    train(model, proc, docs, STEPS, 0)
    test = make(N_TEST, 1000, SEEN)
    print(f"\n--- {STEPS} steps on a 4-bit base. Field accuracy, adapter attached: {score(model, proc, test)[0]['field_accuracy']:.3f}")
    layers = {n: m for n, m in model.named_modules() if hasattr(m, "lora_A")}
    before = {n: dequantize_bnb_weight(m.get_base_layer().weight).float().cpu() for n, m in layers.items()}
    delta = {n: m.get_delta_weight("default").detach().float().cpu() for n, m in layers.items()}
    logging.disable(logging.WARNING)
    merged = model.merge_and_unload()
    logging.disable(logging.NOTSET)
    named = dict(merged.named_modules())
    moved = {n: dequantize_bnb_weight(named[n.replace("base_model.model.", "")].weight).float().cpu() - before[n] for n in layers}
    ratio = torch.tensor([(moved[n] - delta[n]).norm() / delta[n].norm() for n in layers])
    cosine = torch.tensor([torch.nn.functional.cosine_similarity(moved[n].flatten(), delta[n].flatten(), dim=0) for n in layers])
    size = torch.tensor([delta[n].norm() / before[n].norm() for n in layers])
    print(f"over {len(layers)} wrapped layers, medians: update / weight {size.median():.5f}, rounding error / update {ratio.median():.2f}, cosine of the change made with the change wanted {cosine.median():.2f}")
    result = score(merged, proc, test)
    print(f"field accuracy merged: {result[0]['field_accuracy']:.3f}. First reply: {result[1][0][:120]}")
    sys.exit()

# %% What the processor does to a page, and what a target list reaches
page = make(1, 0, SEEN)
print("\n--- image tokens per page by longest edge, against the words of the answer")
for edge in (512, 1024, 2048):
    b = load_processor(edge)(text=proc.apply_chat_template([dict(role="user", content=[dict(type="image")])], tokenize=False), images=[[page[0][0]]], return_tensors="pt")
    print(f"edge {edge}: {b['pixel_values'].shape[1]} tiles, {(b['input_ids'] == proc.tokenizer.convert_tokens_to_ids('<image>')).sum().item()} image tokens")
print(f"answer tokens: {len(proc.tokenizer(answer(page[0][1])).input_ids)}")
try:  # truncation can cut the image tokens, and the image then has nowhere to go
    proc(text=proc.apply_chat_template([dict(role="user", content=[dict(type="image"), dict(type="text", text=PROMPT)])], tokenize=False), images=[[page[0][0]]], truncation=True, max_length=40, return_tensors="pt")
    print("truncating to 40 tokens raised nothing")
except (ValueError, TypeError) as e:
    print(f"truncating to 40 tokens: {type(e).__name__}: {str(e)[:150]}")
print("\n--- one training step, batch 1, by longest edge (mean of three steps, first included)")
for edge in (512, 1024, 2048):
    clear()
    model, big = add_lora(load_model(), TEXT_ONLY), load_processor(edge)
    per_step = train(model, big, page, 3, 0, batch=1)
    print(f"edge {edge}: {per_step:.2f} s/step, driver {driver_gb():.2f} GB")
    del model
clear()
model = load_model()
print(f"\nweights in memory, bf16: {weights_gb():.2f} GB")
total = sum(p.numel() for p in model.parameters())
print(f"\n--- parameters reached, of {total:,}")
for name, targets in (("a suffix list, as in the published recipes", SUFFIXES), ("restricted to the language model", TEXT_ONLY)):
    wrapped = add_lora(load_model(), targets)
    print(f"{name}: {trainable(wrapped):,} trainable, vision adapters {sum(p.numel() for n, p in wrapped.named_parameters() if p.requires_grad and 'vision_model' in n):,}")
    del wrapped
del model
clear()
model = load_model(bits=4)
print(f"weights in memory, 4-bit NF4: {weights_gb():.2f} GB")
del model
clear()

# %% The arms
rows, curves, merges, small_rows = [], [], [], []
ARMS = {
    "LoRA, language model, 400 invoices": dict(n=400),
    "LoRA, language model, 100 invoices": dict(n=100),
    "LoRA, language model, 25 invoices": dict(n=25),
    "LoRA, language and vision": dict(n=400, targets=SUFFIXES),
    "labels: padding and image tokens masked": dict(n=400, mask="padding and image tokens"),
    "labels: padding masked only": dict(n=400, mask="padding only"),
}
for seed in range(args.seeds):
    train_docs = make(400, seed, SEEN)
    slices = {"seen layouts": make(N_TEST, seed + 1000, SEEN),
              "held-out layout": make(N_TEST, seed + 2000, HELD_OUT),
              "new vendor words": make(N_TEST, seed + 3000, SEEN, NEW_STEMS, NEW_TRADES),
              "small print": make(N_TEST, seed + 4000, SEEN, big=18, small=13)}
    val = make(20, seed + 5000, SEEN)
    frozen = load_model()
    for name, prompt in (("frozen, plain prompt", PROMPT), ("frozen, shape shown in prompt", SHOWN)):
        rows.append(dict(seed=seed, arm=name, slice="seen layouts", **score(frozen, proc, slices["seen layouts"], prompt, 400)[0]))  # a limit that does not cut frozen replies
    del frozen
    for arm, kw in ARMS.items():
        clear()
        model = add_lora(load_model(), kw.get("targets", TEXT_ONLY))
        tick = time.time()
        curve = []
        per_step = train(model, proc, train_docs[:kw["n"]], STEPS, seed, mask=kw.get("mask", "answer only"), every=50 if arm.endswith("400 invoices") else None, val=val, curve=curve)
        for c in curve:
            curves.append(dict(seed=seed, **c))
        names = slices if arm.endswith("400 invoices") else ["seen layouts"]
        for s in names:
            rows.append(dict(seed=seed, arm=arm, slice=s, s_per_step=per_step, gb=driver_gb(), trainable=trainable(model), **score(model, proc, slices[s])[0]))
        if arm.endswith("400 invoices"):  # adapter, merged, and reloaded from disk must all read the same
            docs, base = slices["seen layouts"], score(model, proc, slices["seen layouts"])
            with tempfile.TemporaryDirectory() as tmp:
                model.save_pretrained(tmp)
                adapter_mb = size_mb(tmp)
                reloaded = PeftModel.from_pretrained(load_model(), tmp)
                again = score(reloaded, proc, docs)
                del reloaded
            merged = model.merge_and_unload()
            after = score(merged, proc, docs)
            with tempfile.TemporaryDirectory() as tmp:
                merged.save_pretrained(tmp)
                merged_mb = size_mb(tmp)
            merges.append(dict(seed=seed, base="bf16", adapter=base[0]["field_accuracy"], reloaded=again[0]["field_accuracy"], merged=after[0]["field_accuracy"],
                               same_replies_merged=sum(a == b for a, b in zip(base[1], after[1])) / len(docs), adapter_mb=adapter_mb, merged_mb=merged_mb))
            del merged
        del model
        print(f"seed {seed} {arm} done, {time.time() - started:.0f}s", flush=True)

    # Small print: is it the model or the pixels? Same page, same steps, trained and tested at each resolution
    small_train = make(400, seed + 6000, SEEN, big=18, small=13)
    for edge in (512, 1024):
        clear()
        sized = load_processor(edge)
        model = add_lora(load_model(), TEXT_ONLY)
        per_step = train(model, sized, small_train, STEPS, seed, batch=2)
        small_rows.append(dict(seed=seed, edge=edge, s_per_step=per_step, gb=driver_gb(), **score(model, sized, slices["small print"])[0]))
        del model
        print(f"seed {seed} small print at {edge} done, {time.time() - started:.0f}s", flush=True)

    # 4-bit: train on a quantized base, then ask what serves it
    clear()
    model = add_lora(load_model(bits=4), TEXT_ONLY, quantized=True)
    per_step = train(model, proc, train_docs, STEPS, seed)
    docs = slices["seen layouts"]
    base = score(model, proc, docs)
    rows.append(dict(seed=seed, arm="LoRA on a 4-bit base", slice="seen layouts", s_per_step=per_step, gb=driver_gb(), trainable=trainable(model), **base[0]))
    with tempfile.TemporaryDirectory() as tmp:
        model.save_pretrained(tmp)
        full = PeftModel.from_pretrained(load_model(), tmp)
        on_full = score(full, proc, docs)
        del full
    logging.disable(logging.WARNING)
    merged = model.merge_and_unload()
    logging.disable(logging.NOTSET)
    after = score(merged, proc, docs)
    merges.append(dict(seed=seed, base="4-bit", adapter=base[0]["field_accuracy"], reloaded=on_full[0]["field_accuracy"], merged=after[0]["field_accuracy"],
                       same_replies_merged=sum(a == b for a, b in zip(base[1], after[1])) / len(docs)))
    del model, merged
    print(f"seed {seed} 4-bit done, {time.time() - started:.0f}s", flush=True)

# %% Results
res = pd.DataFrame(rows)
cols = ["field_accuracy", "values_found", "parses", "vendor", "number", "issued", "total"]
first = res[res.slice == "seen layouts"]
print("\n--- mean over seeds, seen layouts")
print(first.groupby("arm", sort=False)[cols + ["gb", "trainable"]].mean().round(3).to_string())
print("\n--- standard deviation of field accuracy over seeds, seen layouts")
print(first.groupby("arm", sort=False)["field_accuracy"].std().round(3).to_string())
print("\n--- the 400-invoice model on four slices, mean over seeds")
print(res[res.arm.str.endswith("400 invoices")].groupby("slice", sort=False)[cols].mean().round(3).to_string())
print(res[res.arm.str.endswith("400 invoices")].groupby("slice", sort=False)["field_accuracy"].std().round(3).to_string())
print("\n--- small print, trained on small print, batch 2, by longest edge, mean over seeds")
print(pd.DataFrame(small_rows).groupby("edge")[cols + ["gb"]].mean().round(3).to_string())
if curves:
    print("\n--- during training, 400 invoices, 20 held-back invoices, mean over seeds")
    print(pd.DataFrame(curves).groupby("step")[["train_loss", "field_accuracy", "parses"]].mean().round(3).to_string())
print("\n--- adapter, reloaded and merged on the same 40 invoices, mean over seeds")
print(pd.DataFrame(merges).groupby("base", sort=False).mean(numeric_only=True).drop(columns="seed").round(3).to_string())
print(f"\nall done, {time.time() - started:.0f}s")
