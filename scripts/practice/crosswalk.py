#!/usr/bin/env python3
"""Validate practice/ and programming/drills/ against the curriculum and generate practice/CROSSWALK.md.

    python3 scripts/practice/crosswalk.py           # validate, then write CROSSWALK.md
    python3 scripts/practice/crosswalk.py --check   # validate, exit 1 if CROSSWALK.md is stale

Reads only files git would track (`git ls-files -co --exclude-standard` on both roots), so anything
private or uncleared under them is never read, listed or linked. Run from anywhere in the repo.

Checks, with one line per problem and exit 1 on any:
- every `units:` entry in round and drill frontmatter exists, repo-relative, and is not ignored;
- every relative link in those files resolves, and does not point at an ignored file.
programming/drills/coding/dsa/ is upstream material, so its links are not checked and it has no units.

`units:` accepts an inline list or a YAML block list, of folders or single notes:
    units: [programming/sql, data-analytics/06-applied-analyses/notes/06-sql-for-analytics.md]

RENAME PASSES: `units:` fields and links here use current curriculum folder names. Any scripted
rename of curriculum folders (data-science is next) must include both roots in its rewrite, then
run this script. A missed rename fails here rather than going stale silently.
"""
from __future__ import annotations

import argparse
import re
import subprocess
import sys
from collections import defaultdict
from pathlib import Path
from urllib.parse import unquote

ROOT = Path(__file__).resolve().parents[2]
ROOTS = ("practice/", "programming/drills/")
DRILLS = "programming/drills/"
OUT = ROOT / "practice" / "CROSSWALK.md"
SKIP_LINKS = "programming/drills/coding/dsa/"
FENCE = re.compile(r"^\s*```.*?^\s*```", re.S | re.M)
LINK = re.compile(r"!?\[[^\]\n]*\]\(([^)\s]+)(?:\s+\"[^\"]*\")?\)")
HEADER = """# Crosswalk: curriculum to practice

Generated by `scripts/practice/crosswalk.py` from `units:` frontmatter. Do not edit by hand; run
`make crosswalk`. A unit missing here has no drill or round that names it yet, which does not always
mean it is untested: fields are left out where the mapping is unclear.
"""


def git_lines(*args: str) -> list[str]:
    out = subprocess.run(["git", "-C", str(ROOT), *args], check=True, capture_output=True, text=True)
    return [line for line in out.stdout.splitlines() if line]


def published() -> list[str]:
    return sorted(set(git_lines("ls-files", "-co", "--exclude-standard", *ROOTS)))


def ignored(paths: list[str]) -> set[str]:
    """The subset of repo-relative paths git ignores. Tracked files are never reported."""
    if not paths:
        return set()
    out = subprocess.run(
        ["git", "-C", str(ROOT), "check-ignore", "--stdin"],
        input="\n".join(paths), capture_output=True, text=True,
    )
    if out.returncode not in (0, 1):
        sys.exit(f"git check-ignore failed: {out.stderr.strip()}")
    return set(out.stdout.splitlines())


def units_of(text: str) -> list[str]:
    if not text.startswith("---"):
        return []
    end = text.find("\n---", 3)
    if end < 0:
        return []
    lines = text[3:end].splitlines()
    for i, line in enumerate(lines):
        if not line.startswith("units:"):
            continue
        rest = line[len("units:"):].strip()
        if rest:
            return [u.strip().strip("'\"") for u in rest.strip("[]").split(",") if u.strip()]
        found = []
        for item in lines[i + 1:]:
            if not item.startswith((" ", "-")) or not item.strip().startswith("-"):
                break
            found.append(item.strip()[1:].strip().strip("'\""))
        return found
    return []


def link_targets(text: str) -> list[str]:
    body = FENCE.sub("", text)
    out = []
    for target in LINK.findall(body):
        if re.match(r"[a-zA-Z][a-zA-Z+.-]*:|#|//", target):
            continue
        path = unquote(target.split("#", 1)[0])
        if path:
            out.append(path)
    return out


def validate(files: dict[str, str], publ: set[str]) -> tuple[list[str], dict[str, list[str]]]:
    problems: list[str] = []
    units: dict[str, list[str]] = {}
    pub_dirs = {str(Path(p).parents[i]) for p in publ for i in range(len(Path(p).parents) - 1)}
    pending: list[tuple[str, str]] = []
    for rel, text in files.items():
        found = units_of(text)
        if found:
            units[rel] = found
        for unit in found:
            unit = unit.rstrip("/")
            if not (ROOT / unit).exists():
                problems.append(f"{rel}: unit does not exist: {unit}")
            else:
                pending.append((rel, unit))
        if rel.startswith(SKIP_LINKS):
            continue
        base = (ROOT / rel).parent
        for target in link_targets(text):
            abs_path = (base / target).resolve()
            try:
                to = abs_path.relative_to(ROOT).as_posix()
            except ValueError:
                problems.append(f"{rel}: link leaves the repo: {target}")
                continue
            if to.startswith(ROOTS) or f"{to}/" in ROOTS:
                if to not in publ and to not in pub_dirs and to != "practice/CROSSWALK.md":
                    problems.append(f"{rel}: link to unpublished or missing file: {target}")
            elif not abs_path.exists():
                problems.append(f"{rel}: broken link: {target}")
            else:
                pending.append((rel, to))
    bad = ignored(sorted({to for _, to in pending}))
    for rel, to in pending:
        if to in bad:
            problems.append(f"{rel}: points at an ignored path: {to}")
    return sorted(set(problems)), units


def label(rel: str) -> str:
    parts = rel.split("/")
    if rel.startswith("practice/interviewing/rounds/") and len(parts) > 4:
        return parts[3] if parts[-1] == "README.md" else f"{parts[3]}/{Path(parts[-1]).stem}"
    return Path(rel).stem


def crosswalk_link(rel: str) -> str:
    """A repo-relative path as CROSSWALK.md, which sits in practice/, links to it."""
    return rel.removeprefix("practice/") if rel.startswith("practice/") else f"../{rel}"


def unit_link(unit: str) -> str:
    target = ROOT / unit
    if target.is_dir() and (target / "README.md").exists():
        return f"[`{unit}`](../{unit}/README.md)"
    return f"[`{unit}`](../{unit})"


def generate(units: dict[str, list[str]]) -> str:
    table: dict[str, dict[str, set[str]]] = defaultdict(lambda: {"rounds": set(), "drills": set()})
    for rel, found in units.items():
        kind = "drills" if rel.startswith(DRILLS) else "rounds"
        for unit in found:
            table[unit.rstrip("/")][kind].add(rel)
    lines = [HEADER]
    subjects: dict[str, list[str]] = defaultdict(list)
    for unit in table:
        subjects[unit.split("/")[0]].append(unit)
    for subject in sorted(subjects):
        lines += [f"## {subject}", "", "| Unit | Rounds | Drills |", "|---|---|---|"]
        for unit in sorted(subjects[subject]):
            cells = [
                ", ".join(f"[{label(r)}]({crosswalk_link(r)})" for r in sorted(table[unit][k])) or "-"
                for k in ("rounds", "drills")
            ]
            lines.append(f"| {unit_link(unit)} | {cells[0]} | {cells[1]} |")
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="do not write; exit 1 if CROSSWALK.md is stale")
    args = parser.parse_args()

    publ = set(published())
    files = {rel: (ROOT / rel).read_text(encoding="utf-8") for rel in sorted(publ)
             if rel.endswith(".md") and rel != "practice/CROSSWALK.md" and (ROOT / rel).exists()}
    problems, units = validate(files, publ)
    for problem in problems:
        print(problem)
    print(f"crosswalk: {len(files)} markdown files, {len(units)} with units, "
          f"{len({u for us in units.values() for u in us})} distinct units, {len(problems)} problems")
    if problems:
        return 1
    text = generate(units)
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("crosswalk: practice/CROSSWALK.md is stale; run make crosswalk")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"crosswalk: wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
